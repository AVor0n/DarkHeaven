import { TileSvg } from '../board/Tile';

function Tile({
  kind,
  pit = false,
}: {
  kind: Parameters<typeof TileSvg>[0]['kind'];
  pit?: boolean;
}) {
  return (
    <span className="rules__tile">
      <TileSvg kind={kind} rot={0} pit={pit} seed={7} />
    </span>
  );
}

